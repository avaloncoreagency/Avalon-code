"use client";
import { useActionState } from "react";
import { totpEnrollment, type EnrollState } from "@/app/admin/mfa-actions";
import type { Lang } from "@/lib/i18n";
import s from "./os.module.css";

const ERRORS: Record<string, [string, string]> = {
  code: ["Código no válido. Usa el código actual de la app.", "Invalid code. Use the app's current code."],
  throttled: ["Demasiados intentos. Espera unos minutos.", "Too many attempts. Wait a few minutes."],
  exists: ["Ya tienes un factor verificado.", "You already have a verified factor."],
  failed: ["No se pudo iniciar el registro. Inténtalo de nuevo.", "Could not start enrollment. Try again."],
  unauthorized: ["Tu sesión expiró. Vuelve a entrar.", "Your session expired. Sign in again."],
};

/** Opt-in TOTP enrollment: QR → first code → factor verified. */
export function MfaEnroll({ lang }: { lang: Lang }) {
  const es = lang === "es";
  const [current, act, pending] = useActionState(totpEnrollment, { step: "idle" } as EnrollState);
  const error = "error" in current && current.error ? ERRORS[current.error]?.[es ? 0 : 1] : null;

  if (current.step === "done") return <p role="status"><strong>{es ? "Verificación en dos pasos activada." : "Two-step verification enabled."}</strong> {es ? "La próxima vez que inicies sesión se pedirá el código." : "Your next sign-in will ask for the code."}</p>;

  if (current.step === "scan") return (
    <div className={s.form}>
      <ol className={s.meta} style={{ paddingLeft: 18 }}>
        <li>{es ? "Abre tu app de autenticación (Google Authenticator, 1Password, Authy, Microsoft Authenticator…)." : "Open your authenticator app (Google Authenticator, 1Password, Authy, Microsoft Authenticator…)."}</li>
        <li>{es ? "Escanea el código QR o introduce la clave manualmente." : "Scan the QR code or enter the key manually."}</li>
        <li>{es ? "Escribe el código de 6 dígitos para confirmar." : "Type the 6-digit code to confirm."}</li>
      </ol>
      {/* eslint-disable-next-line @next/next/no-img-element -- data: SVG generated by Supabase */}
      <img src={current.qr} alt={es ? "Código QR para la app de autenticación" : "QR code for the authenticator app"} width={180} height={180} style={{ background: "#fff", borderRadius: 12, padding: 8 }} />
      <p className={s.meta}>{es ? "Clave manual" : "Manual key"}: <code style={{ userSelect: "all", wordBreak: "break-all" }}>{current.secret}</code></p>
      <form action={act} className={s.form}>
        <input type="hidden" name="intent" value="confirm" />
        <label className={s.label} htmlFor="mfa-code">{es ? "Código de 6 dígitos" : "6-digit code"}</label>
        <input id="mfa-code" className={s.input} name="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9 ]{6,7}" maxLength={7} required />
        {error && <p className={s.meta} role="alert" style={{ color: "var(--danger)" }}>{error}</p>}
        <div className={s.actions}><button className={s.btnPrimary} type="submit" disabled={pending}>{pending ? "…" : es ? "Confirmar y activar" : "Confirm and enable"}</button></div>
      </form>
    </div>
  );

  return (
    <form action={act} className={s.form}>
      <input type="hidden" name="intent" value="start" />
      <p className={s.meta}>{es ? "Recomendado para cuentas propietarias. Necesitarás una app de autenticación en tu teléfono." : "Recommended for owner accounts. You will need an authenticator app on your phone."}</p>
      {error && <p className={s.meta} role="alert" style={{ color: "var(--danger)" }}>{error}</p>}
      <div className={s.actions}><button className={s.btnPrimary} type="submit" disabled={pending}>{pending ? "…" : es ? "Activar verificación en dos pasos" : "Enable two-step verification"}</button></div>
    </form>
  );
}
